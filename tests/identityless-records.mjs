import './seliga.mjs';
import assert from 'node:assert/strict';
const E=window.Edu;
const ghost={id:'ghost',registration:'',name:'',status:'Matriculado',rosterStudent:true,documents:{},history:[],sources:{}};
const valid={...ghost,id:'valid',registration:'001',name:'Nome Confirmado'};
assert.equal(E.isActiveRosterStudent(ghost),false);
assert.equal(E.isActiveRosterStudent(valid),true);
assert.equal(E.isActiveRosterStudent({...valid,status:'Transferido'}),false);
assert.equal(E.isActiveRosterStudent({...valid,name:'001'}),false);
assert.equal(E.enrollmentSummary([ghost,valid],{records:[]}).total,1);
assert.equal(E.metrics(ghost,2026).score,null);
assert.equal(E.metrics({...valid,classes:100,absences:0},2026).score,0);
assert.equal(E.metrics({...valid,classes:100,absences:30},2026).score,50);
const proof={...ghost,history:[{confirmedIdentity:{registration:'002',name:'Fonte Confirmada'}}]};
const recovered=E.recoverStudentNames([proof],[]);
assert.equal(recovered.recovered,1);assert.equal(recovered.students[0].id,'ghost');assert.equal(recovered.students[0].registration,'002');assert.equal(recovered.students[0].name,'Fonte Confirmada');
assert.equal(E.recoverStudentNames(recovered.students,[]).recovered,0);
assert.equal(E.recoverStudentNames([proof,{...valid,registration:'002'}],[]).recovered,0);
assert.equal(E.recoverStudentNames([proof,{...proof,id:'other'}],[]).recovered,0);
assert.equal(E.recoverStudentNames([{...proof,history:[...proof.history,{confirmedIdentity:{registration:'003',name:'Outra Fonte'}}]}],[]).recovered,0);
console.log('PASS: unidentified records excluded from active/enrollment indicators; unknown score distinct from zero; unique confirmed identities recovered without duplicates or lost IDs.');
const blankName={...valid,id:'missing-name',registration:'003',name:''};
const confirmation={registration:'003',name:'Nome Da Confirmacao'};
const before=E.enrollmentSummary([blankName],{records:[confirmation]});
assert.equal(before.outsideRoster.length,1);assert.match(before.outsideRoster[0].reason,/Identidade incompleta/);
const repaired=E.recoverStudentNames([blankName],[],[confirmation]);
assert.equal(repaired.recovered,1);assert.equal(repaired.students[0].id,blankName.id);
assert.equal(E.enrollmentSummary(repaired.students,{records:[confirmation]}).count,1);
assert.equal(E.enrollmentSummary(repaired.students,{records:[confirmation]}).outsideRoster.length,0);
assert.equal(E.recoverStudentNames([blankName],[{registration:'003',name:'Nome Divergente'}],[confirmation]).recovered,0);
