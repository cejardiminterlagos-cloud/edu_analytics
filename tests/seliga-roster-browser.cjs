const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {chromium}=require('playwright'),{pathToFileURL}=require('node:url');
(async()=>{
 const app=path.resolve(__dirname,'../index.html'),html=fs.readFileSync(app,'utf8');
 const seed=JSON.parse(html.match(/<script id="initial-data" type="application\/json">([\s\S]*?)<\/script>/)[1]);
 global.window={};vm.runInThisContext(html.match(/<script id="engine">([\s\S]*?)<\/script>/)[1]);
 const file=process.argv[2]||'C:/Users/Bruno/Downloads/9A.xlsx - Consolidado notas.csv';
 const csv=window.Edu.consolidatedGrades(window.Edu.parseCSV(fs.readFileSync(file,'utf8')));
 const student=(registration,name,group='9º Ano A')=>({id:registration,registration,name,group,series:'9EF',status:'MATRICULADO',rosterStudent:true,rosterYear:'2026',rosterDate:'2026-03-01',documents:{},sources:{},history:[]});
 seed.referenceYear=2026;
 const roster=csv.data.map(r=>student(r[1],r[2]));
 const [moved,missing,transferred,unreviewed]=roster;
 missing.schoolYears={2025:{status:'MATRICULADO',group:'8º Ano A',series:'8EF',rosterDate:'2025-03-01'}};
 seed.students=roster;
 seed.grades=[{year:2026,registration:moved.registration,name:moved.name,group:'9º Ano B',discipline:csv.blocks[0].name,notes:[5,5,5]}];
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 try{
  const p=await browser.newPage();await p.route('https://**',r=>r.abort());
  await p.addInitScript(state=>{if(!sessionStorage.seeded){localStorage.setItem('eduanalytics_db_v1',JSON.stringify(state));sessionStorage.seeded='1';}},seed);
  await p.goto(pathToFileURL(app).href+'#seliga');
  if(await p.locator('#cloud-gate').isVisible())await p.locator('[data-action=cloud-local-only]').click();
  await p.locator('#grades-group').selectOption('9º Ano A');
  assert.match(await p.locator('.grade-matrix').innerText(),/5,0/);
  await p.locator('details.panel').evaluate(e=>e.open=true);
  await p.locator('#grades-file').setInputFiles(file);
  await p.locator('#grades-upload button[type=submit]').click();
  await p.locator('#grades-consolidated button').click();
  assert.match(await p.locator('#grades-preview').innerText(),/9º Ano A · 30 estudante/);
  await p.locator('[data-action=grades-apply]').click();
  await p.waitForFunction(()=>EduApp.getState().grades.length===300);
  assert.equal(await p.locator('.grade-matrix tbody tr').count(),30);
  const openImport=()=>p.getByRole('link',{name:'Importar e cruzar',exact:true}).click();
  await openImport();
  const uploadRoster=async(name,lines)=>{
   await p.locator('#batch-input').setInputFiles({name,mimeType:'text/csv',buffer:Buffer.from('CGM;Nome;Turma;Série;Situação;Data do relatório\n'+lines.join('\n'))});
   await p.locator('[data-batch-field=completeDate]').waitFor();
  };
  const line=(s,g,status,date)=>[s.registration,s.name,g,'9EF',status,date].join(';');
  await uploadRoster('lista.csv',[line(moved,'9º Ano B','MATRICULADO','01/10/2026'),line(transferred,'9º Ano A','TRANSFERIDO','01/10/2026'),...roster.slice(4).map(s=>line(s,s.group,'MATRICULADO','01/10/2026'))]);
  await p.locator('[data-batch-field=completeDate]').fill('2026-10-01');
  await p.locator('[data-action=batch-preview]').click();
  await p.getByRole('checkbox',{name:new RegExp(missing.registration)}).check();
  assert.equal(await p.locator('[data-batch-inactive]').count(),2);
  await p.locator('[data-action=batch-apply]').click();
  await p.waitForFunction(()=>EduApp.getState().imports.some(r=>r.file==='lista.csv'));
  const state=await p.evaluate(()=>EduApp.getState());
  const find=s=>state.students.find(x=>x.registration===s.registration);
  assert.equal(find(missing).schoolYears[2026].status,'Inativo por ausência confirmada');
  assert.equal(find(missing).schoolYears[2025].status,'MATRICULADO');
  assert.equal(find(unreviewed).status,'MATRICULADO');
  assert.equal(state.grades.length,300);
  await p.getByRole('link',{name:'Se Liga!',exact:true}).click();
  await p.locator('#grades-group').selectOption('9º Ano B');
  assert.equal(await p.locator('.grade-matrix tbody tr').count(),1);
  assert.match(await p.locator('.grade-matrix').innerText(),new RegExp(moved.registration));
  await p.locator('#grades-group').selectOption('9º Ano A');
  const matrix=await p.locator('.grade-matrix').innerText();
  assert.ok(!matrix.includes(missing.registration)&&!matrix.includes(transferred.registration)&&matrix.includes(unreviewed.registration));
  await openImport();
  await uploadRoster('historico.csv',[line(missing,'8º Ano B','MATRICULADO','01/10/2025')]);
  await p.locator('[data-action=batch-preview]').click();
  assert.equal(await p.locator('[data-batch-inactive]').count(),0);
  await p.locator('[data-action=batch-apply]').click();
  await p.waitForFunction(()=>EduApp.getState().imports.some(r=>r.file==='historico.csv'));
  const updated=await p.evaluate(id=>EduApp.getState().students.find(s=>s.registration===id),missing.registration);
  assert.equal(updated.schoolYears[2026].status,'Inativo por ausência confirmada');
  assert.equal(updated.schoolYears[2025].group,'8º Ano B');
  console.log('PASS: 9A CSV, 300 records, live class, transfer, confirmed absence, unselected absence and historical import.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});

