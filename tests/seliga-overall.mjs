import './seliga.mjs';
import assert from 'node:assert/strict';
const E=window.Edu;
const r=(registration,discipline,notes,group='8 A',year=2026)=>({registration,discipline,notes,group,year});
const rows=[r('1','Arte',[5,5,5]),r('1','Matemática',[8,8,8])];
assert.equal(E.overallGrade(rows,'1','8 A',2026,['Arte','Matemática']).mean,6.5);
assert.equal(E.overallGrade(rows,'1','8 A',2026,['Arte','Matemática']).level.key,'basic');
assert.equal(E.overallGrade([...rows,r('2','História',[8,8,8])],'1','8 A',2026,['Arte','Matemática']).level.key,'missing');
assert.equal(E.overallGrade([r('1','Arte',[0,0,0])],'1','8 A',2026,['Arte']).mean,0);
assert.equal(E.overallGrade([r('1','Arte',[8,null,8])],'1','8 A',2026,['Arte','Matemática']).mean,null);
assert.equal(E.overallGrade([...rows,r('2','História',[8,8,8],'9 A')],'1','8 A',2026,['Arte','Matemática']).mean,6.5);
assert.equal(E.overallGrade(rows,'1','8 A',2025).mean,null);
assert.equal(E.overallGrade([],'1','8 A',2026).total,0);
assert.equal(E.overallGrade([r('1','Arte',[6.9,7,7])],'1','8 A',2026,['Arte']).level.key,'basic');
console.log('PASS: general mean, missing disciplines/terms, zero, years, classes and no rounding before classification.');

assert.equal(E.overallGrade(rows,'1','8 A',2026).mean,null);
assert.equal(E.overallGrade(rows,'1','8 A',2026,['Arte','Matemática','História']).mean,null);
assert.equal(E.overallGrade(rows,'1','8 A',2026,['Arte']).confirmed,false);
const pending=E.overallGrade([r('1','Educação Física',[8,8,null])],'1','8 A',2026,['Educação Física']);
assert.equal(pending.level.key,'missing');
assert.deepEqual(pending.pending,[{discipline:'Educação Física',terms:['T3']}]);
assert.deepEqual(E.overallGrade([r('1','Arte',[0,0,0])],'1','8 A',2026,['Arte']).pending,[]);
